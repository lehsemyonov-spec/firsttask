"""Шаг 5 (версия 2, после критики skeptic). Поток ВПЕРВЫЕ подходящих групп и условная экономика O3.
Единица — группа: учитывается первый подходящий случай (низкий остаток доли у одного участника) в группе
после начала наблюдения; номер этого участника — единица результата. Повторные случаи не создают новых единиц.
Все множители — допущения до выгрузки I кв. (U1, U3, U10, U11).
Запуск: python projects/svyaz-blizkih/analysis/economics.py
"""
RATE = 500              # руб. за доп. оплаченный месяц номера (S1, стр. 9)
CONNECTED_Q2 = 7_000    # подключённых групп во II кв. (между 6 500 и 8 000, S1 стр. 3) — допущение
CONNECTED_H2 = 7_500    # во II полугодии — допущение
HOLDOUT = 0.10          # допущение команды: 10 % подходящих групп в группе сравнения (бриф, стр. 8, долю не задаёт)

# v3 (2026-11-22): совместимые тарифы 40 % групп — F45 (S5); согласия 50–100 % — допущение (U11). v2 было 0,40/0,70
scope = {"низ": 0.40 * 0.50, "верх": 0.40 * 1.00}
hazard = {"низ": 0.15, "верх": 0.30}  # доля ещё «нетронутых» групп, у которых за месяц впервые случается низкий остаток (U1)
retained = {"низ": 0.0, "верх": 0.05}  # доля номеров с первым случаем, которые без услуги перестали бы платить, а с ней платят (U3); низ 0 — F34

def first_time_by_week(pool, h_month, weeks):
    h_week = 1 - (1 - h_month) ** (1 / 4.33)
    left, out = pool, []
    for _ in range(weeks):
        new = left * h_week
        out.append(new)
        left -= new
    return out

print("== Пилот: поток впервые подходящих групп с середины мая (II кв.) ==")
need = {"30%->20%": 588, "30%->22%": 942, "12%->9%": 3_276,
        # порог плана проверки: −25 % относительно (шаг 6)
        "30%->22,5%": 1_080, "20%->15%": 1_812, "15%->11,25%": 2_544}
for k in ("низ", "верх"):
    pool = CONNECTED_Q2 * scope[k]
    flow = first_time_by_week(pool, hazard[k], 52)
    print(f"{k}: подходящих групп {pool:.0f}; 1-я неделя {flow[0]:.0f}, 6-я {flow[5]:.0f}, 12-я {flow[11]:.0f}")
    cum = 0
    reached = {}
    for w, f in enumerate(flow, 1):
        cum += f
        for name, n in need.items():
            if name not in reached and cum >= n:
                reached[name] = w
    for name, n in need.items():
        print(f"   {name}: {n} групп — " + (f"набор {reached[name]} нед." if name in reached else "не набирается за 52 нед."))

print("\n== Подходящая база в абсолютных числах ==")
for k in ("низ", "верх"):
    for g in (8_000,):
        print(f"{k}: {g*scope[k]:.0f} групп = {g*scope[k]/100_000:.1%} от 100 тыс. домохозяйств")

print("\n== Вклад удержания в плановом году: расширение с 1 августа (только основной ход) ==")
# месяцы до конца года для когорты месяца: авг->4, сен->3, окт->2, ноя->1, дек->0
remaining = [4, 3, 2, 1, 0]
for k in ("низ", "верх"):
    left = CONNECTED_H2 * scope[k] * (1 - HOLDOUT)
    months = 0
    for r in remaining:
        new = left * hazard[k]
        left -= new
        months += new * retained[k] * r
    print(f"{k}: доп. оплаченных месяцев {months:.0f} = {months*RATE/1e6:.2f} млн руб.")

print("\n== Второй год (12 мес. работы на расширенном охвате, база без роста) ==")
for k in ("низ", "верх"):
    pool = CONNECTED_H2 * scope[k] * (1 - HOLDOUT)
    left, months = pool, 0
    for m in range(12):
        new = left * hazard[k]
        left -= new
        months += new * retained[k] * (12 - m - 1)
    # номера, удержанные в 1-м году, сюда не входят — оценка не является верхней границей
    print(f"{k}: {months:.0f} доп. месяцев = {months*RATE/1e6:.2f} млн руб.")

print("\n== Граница решения ==")
for c in (0.5, 1, 2):
    print(f"разработка {c} млн руб. -> нужно {c*1e6/RATE:.0f} доп. оплаченных месяцев")
