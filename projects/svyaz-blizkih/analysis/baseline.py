"""Расчёты по исходным показателям брифа (S1, стр. 3, 6, 9). Все числа учебные.
Запуск: python projects/svyaz-blizkih/analysis/baseline.py
"""

# S1, стр. 3
HH_ACCESSIBLE = 100_000      # доступные домохозяйства
OWN_ACCESSIBLE = 40_000      # доступные владельцы нескольких номеров
groups = {"план_база": 7_500, "оценка_база": 6_500, "без_изм": 8_000, "цель": 12_000}
active = {"план_база": 5_000, "оценка_база": 4_000, "без_изм": 5_000, "цель": 8_000}
owners = {"план_база": 1_000, "оценка_база": 800, "без_изм": 1_000, "цель": 2_000}
gp = {"план_база": 282, "оценка_база": 275, "без_изм": 279, "цель": 285}  # млн руб./год
RATE = 500  # руб. валовой прибыли за доп. оплаченный месяц номера (стр. 9)

print("== Охват доступной базы (группа ~ домохозяйство) ==")
for k in groups:
    print(f"{k:12} семьи {groups[k]/HH_ACCESSIBLE:6.1%}   владельцы {owners[k]/OWN_ACCESSIBLE:6.1%}")

print("\n== Доля активных среди подключённых ==")
for k in groups:
    print(f"{k:12} {active[k]/groups[k]:6.1%}")

print("\n== Разложение отставания активных групп в базовом году (план -> оценка) ==")
share_plan = active["план_база"] / groups["план_база"]
share_fact = active["оценка_база"] / groups["оценка_база"]
gap = active["план_база"] - active["оценка_база"]
from_volume = (groups["план_база"] - groups["оценка_база"]) * share_plan
from_share = groups["оценка_база"] * (share_plan - share_fact)
print(f"отставание {gap}: из-за меньшего числа групп {from_volume:.0f}, из-за доли активных {from_share:.0f}")

print("\n== Цель по активным при разном числе подключённых ==")
for g in (8_000, 10_000, 12_000):
    print(f"подключено {g}: нужна доля активных {active['цель']/g:6.1%}")
for s in (0.625, 0.70, 0.75):
    print(f"при 8 000 подключённых и доле {s:.1%}: активных {8_000*s:.0f}")

print("\n== Граница по прибыли ==")
gap_gp = (gp["цель"] - gp["без_изм"]) * 1_000_000
months = gap_gp / RATE
print(f"разрыв {gap_gp/1e6:.0f} млн руб. -> {months:.0f} доп. оплаченных месяцев")
for m_left in (9, 6, 3):
    print(f"если эффект действует {m_left} мес. до конца года: нужно {months/m_left:.0f} номеров, удержанных сверх обычного на весь срок")

print("\n== Прирост по семьям (стр. 6) ==")
print(f"чистый прирост к цели: {groups['цель']-groups['оценка_база']}; разрыв к 'без изменений': {groups['цель']-groups['без_изм']}")
