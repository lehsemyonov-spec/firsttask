"""Условный расчёт эффекта O3 на активные группы (шаг 4). Все множители — допущения до выгрузки I кв.
Формула: прирост активных = подключённые x доля в охвате x доля групп со случаем за месяц
         x доля групп, которые без сигнала были бы неактивны x доля откликнувшихся организаторов.
Запуск: python projects/svyaz-blizkih/analysis/options_calc.py
"""
CONNECTED = 8_000   # подключённых групп без изменений на конец года (S1, стр. 3)
ACTIVE_BASE = 5_000

# (низ, верх) и основание границ
# v3 (2026-11-22): совместимых тарифов 40 % групп — факт F45 (S5); доля согласий — допущение 50–100 % (U11)
# v2 было: scope = (0.40, 0.70) как общее допущение
COMPATIBLE = 0.40
CONSENT = (0.50, 1.00)
scope = (COMPATIBLE * CONSENT[0], COMPATIBLE * CONSENT[1])   # 0,20 … 0,40
case = (0.15, 0.30)       # доля групп со случаем низкого остатка за месяц; допущение (U1)
inactive = (0.20, 0.375)   # верх ограничен долей неактивных в целом: 1 - 5000/8000 = 37,5 %
respond = (0.30, 0.50)    # доля организаторов, выделивших по сигналу; допущение, проверяется пилотом

HOLDOUT = 0.10  # допущение команды: 10 % подходящих групп остаются в группе сравнения (бриф, стр. 8, требует группу сравнения, долю не задаёт)

def uplift(i):
    return CONNECTED * scope[i] * (1 - HOLDOUT) * case[i] * inactive[i] * respond[i]

lo, hi = uplift(0), uplift(1)
print(f"прирост активных групп в декабре: {lo:.0f} ... {hi:.0f}")
print(f"доля активных: {ACTIVE_BASE/CONNECTED:.1%} -> {(ACTIVE_BASE+lo)/CONNECTED:.1%} ... {(ACTIVE_BASE+hi)/CONNECTED:.1%}")
print(f"разрыв до цели 8 000 активных остаётся: {8000-ACTIVE_BASE-hi:.0f} ... {8000-ACTIVE_BASE-lo:.0f}")
# основной ход: середина каждого допущения
mid_scope = COMPATIBLE * 0.75
mid = CONNECTED * mid_scope * (1 - HOLDOUT) * 0.225 * 0.2875 * 0.40
print(f"основной ход (середины: охват {mid_scope:.0%} = 40 % x согласия 75 %, случай 22,5 %, неактивны 28,75 %, отклик 40 %): +{mid:.0f} -> {ACTIVE_BASE+mid:.0f} активных")
